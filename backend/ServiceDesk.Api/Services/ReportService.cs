using ClosedXML.Excel;
using Microsoft.EntityFrameworkCore;
using ServiceDesk.Api.Common;
using ServiceDesk.Api.Data;
using ServiceDesk.Api.Dtos;
using ServiceDesk.Api.Models;

namespace ServiceDesk.Api.Services;

public interface IReportService
{
    Task<byte[]> ExportTicketsAsync(UserContext ctx, TicketQuery query);
}

public class ReportService(AppDbContext db, ILogger<ReportService> logger) : IReportService
{
    private const int MaxRows = 5000;

    public async Task<byte[]> ExportTicketsAsync(UserContext ctx, TicketQuery query)
    {
        if (!ctx.IsStaff) throw new ForbiddenException("Reports are available to agents and admins only.");

        var now = DateTime.UtcNow;
        var rows = await db.Tickets.AsNoTracking()
            .ApplyFilters(query, now)
            .ApplySort(query.SortBy, query.Desc)
            .Take(MaxRows)
            .Select(t => new
            {
                t.Id, t.Title, t.Status, t.Priority, Category = t.Category.Name,
                CreatedBy = t.CreatedBy.FullName,
                AssignedTo = t.AssignedTo == null ? "" : t.AssignedTo.FullName,
                t.CreatedAt, t.DueAt, t.ResolvedAt
            }).ToListAsync();

        using var workbook = new XLWorkbook();
        var sheet = workbook.Worksheets.Add("Tickets");
        string[] headers = { "ID", "Title", "Status", "Priority", "Category", "Created By", "Assigned To", "Created (UTC)", "Due (UTC)", "Resolved (UTC)", "SLA Breached" };
        for (var i = 0; i < headers.Length; i++) sheet.Cell(1, i + 1).Value = headers[i];
        sheet.Row(1).Style.Font.Bold = true;
        sheet.Row(1).Style.Fill.BackgroundColor = XLColor.LightGray;

        var r = 2;
        foreach (var t in rows)
        {
            var breached = t.ResolvedAt.HasValue ? t.ResolvedAt.Value > t.DueAt
                : t.DueAt < now;
            sheet.Cell(r, 1).Value = t.Id;
            sheet.Cell(r, 2).Value = t.Title;
            sheet.Cell(r, 3).Value = t.Status.ToString();
            sheet.Cell(r, 4).Value = t.Priority.ToString();
            sheet.Cell(r, 5).Value = t.Category;
            sheet.Cell(r, 6).Value = t.CreatedBy;
            sheet.Cell(r, 7).Value = t.AssignedTo;
            sheet.Cell(r, 8).Value = t.CreatedAt;
            sheet.Cell(r, 9).Value = t.DueAt;
            if (t.ResolvedAt.HasValue) sheet.Cell(r, 10).Value = t.ResolvedAt.Value;
            sheet.Cell(r, 11).Value = breached ? "Yes" : "No";
            r++;
        }
        sheet.Range(2, 8, Math.Max(r - 1, 2), 10).Style.DateFormat.Format = "yyyy-mm-dd hh:mm";
        sheet.SheetView.FreezeRows(1);
        double[] widths = { 7, 38, 13, 11, 18, 20, 20, 18, 18, 18, 13 };
        for (var i = 0; i < widths.Length; i++) sheet.Column(i + 1).Width = widths[i];

        using var stream = new MemoryStream();
        workbook.SaveAs(stream);
        logger.LogInformation("Excel report with {Rows} rows generated by user {UserId}", rows.Count, ctx.Id);
        return stream.ToArray();
    }
}
